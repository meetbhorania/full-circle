"""Build switch/full-circle.template.yaml from the agent and room files.

The template is generated, never hand-edited, so it always matches the
instructions the agents actually run with.

    python3 scripts/build_template.py
"""
from pathlib import Path
import re
import yaml

ROOT = Path(__file__).resolve().parent.parent
SW = ROOT / "switch"


def instructions(md: str) -> str:
    return md.split("## Instructions", 1)[1].strip() + "\n"


def below_rule(md: str) -> str:
    return md.split("\n---\n", 1)[1].strip() + "\n"


def role_text(md: str) -> str:
    m = re.search(r"role instructions:\n\n> (.+)", md)
    return m.group(1).strip()


def table(md: str, key: str) -> str:
    m = re.search(rf"\| {key} \| (.+?) \|", md)
    return m.group(1).strip() if m else ""


AGENTS = [  # name, file, addressing
    ("concierge", "concierge.md", "anyone"),
    ("repro", "repro.md", "owner-agents"),
    ("fixer", "fixer.md", "owner-agents"),
    ("reviewer", "reviewer.md", "owner-agents"),
    ("releaser", "release-manager.md", "owner-agents"),
    ("ledger", "ledger.md", "owner-agents"),
]

agents = []
for name, fname, addressing in AGENTS:
    md = (SW / "agents" / fname).read_text()
    agents.append({
        "name": name,
        "display_name": name,
        "description": table(md, "Description"),
        "addressing": addressing,
        "provider": "{provider}",
        "location": "{location}",
        "directory": "{repo_dir}",
        "instructions": instructions(md),
    })

reviewer_md = (SW / "agents" / "reviewer.md").read_text()
releaser_md = (SW / "agents" / "release-manager.md").read_text()
policy_md = (SW / "documents" / "refund-policy.md").read_text()
policy_body = policy_md.split("\n\n", 2)[2].strip() + "\n"  # drop title + note line

doc = {
    "version": 1,
    "params": {
        "repo_dir": {
            "type": "directory",
            "label": "Your full-circle clone",
            "description": "Absolute path to your clone of github.com/meetbhorania/full-circle. Every agent works here.",
        },
        "team_app": {
            "type": "bridge",
            "label": "Team messaging app",
            "description": "Where brew-team lives. Customers never see it.",
            "default": ["Mattermost", "$first"],
        },
        "customer_app": {
            "type": "bridge",
            "label": "Customer messaging app",
            "description": "Where customers reach the concierge (we use Discord).",
            "default": ["$first"],
        },
        "provider": {"type": "provider", "default": ["claude"], "input": "advanced"},
        "location": {"type": "location", "default": "local", "input": "advanced"},
    },
    "agents": agents,
    "group": {
        "name": "Full Circle",
        "description": "Customer message to deployed fix and refund, with a person approving every risky step.",
    },
    "rooms": [
        {
            "name": "brew-team",
            "description": "Where the Brew & Co team (people and agents) handles customer issues from report to fix.",
            "bridge": "{team_app}",
            "channel_type": "channel_private",
            "instructions": below_rule((SW / "rooms" / "brew-team.md").read_text()),
            "agents": [a["name"] for a in agents],
            "users": ["{$creator}"],
            "roles": [
                {"name": "code-review", "exclusive": False, "instructions": role_text(reviewer_md)},
                {"name": "release-manager", "exclusive": True, "instructions": role_text(releaser_md)},
            ],
            "docs": [{
                "name": "refund-policy",
                "description": "Brew & Co refund rules",
                "instructions": "The refund rules. Read this before proposing any refund or credit. Never go beyond it.",
                "content": policy_body,
            }],
            "kickoff": "@reviewer take the role code-review. @releaser take the role release-manager. Each of you reply with one line once you hold it.\n",
        },
        {
            "name": "help",
            "description": "Brew & Co customer help. Only the concierge speaks here.",
            "bridge": "{customer_app}",
            "channel_type": "channel_public",
            "instructions": below_rule((SW / "rooms" / "brew-help.md").read_text()),
            "agents": ["concierge", "releaser"],
            "users": ["{$creator}"],
        },
    ],
    "links": [{"from": "brew-team", "to": "help", "label": "customer support"}],
}

header = """# Full Circle: the whole team in one template.
#
# Creates six agents (concierge, repro, fixer, reviewer, releaser, ledger),
# the private team room "brew-team" with its roles and refund policy, the
# customer room "help", and the link between them.
#
# Generated by scripts/build_template.py from switch/agents, switch/rooms and
# switch/documents. Edit those files, not this one.
#
# Use it: Switch Console -> Templates -> Import template -> this file -> Use.
"""

class Lit(str): ...
def lit(dumper, data): return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
yaml.add_representer(Lit, lit)
def mark(o):
    if isinstance(o, dict): return {k: mark(v) for k, v in o.items()}
    if isinstance(o, list): return [mark(v) for v in o]
    if isinstance(o, str) and "\n" in o: return Lit(o)
    return o

out = SW / "full-circle.template.yaml"
out.write_text(header + "\n" + yaml.dump(mark(doc), sort_keys=False, allow_unicode=True, width=100))
print(f"wrote {out.relative_to(ROOT)}")
